async def _call_local(session: aiohttp.ClientSession, prompt: str) -> str:
    """
    Make an API call to a locally hosted LLM endpoint.

    Args:
        session (aiohttp.ClientSession): The HTTP client session.
        prompt (str): The full diagnostic prompt.

    Returns:
        str: The response content or None.
    """
    model = config.get('llm_model') or "llama3"
    local_url = config.get('llm_local_url', 'http://localhost:11434/api/generate')
    payload = {
        "model": model,
        "prompt": prompt,
        "stream": False
    }
    async with session.post(local_url, json=payload, timeout=60) as resp:
        if resp.status == 200:
            data = await resp.json()
            return data.get('response', '').strip()
        return None
